export const errorCodeSchema = z.enum(ERROR_CODES);
export type ErrorCode = z.infer<typeof errorCodeSchema>;
const nonnegativeInteger = z.number().int().nonnegative();
export const safeParamsSchema = z.strictObject({
  min: z.number().optional(),
  max: z.number().optional(),
  limit: z.number().optional(),
  actual: z.number().optional(),
  expectedRevision: nonnegativeInteger.optional(),
  currentRevision: nonnegativeInteger.optional(),
  row: nonnegativeInteger.optional(),
  column: z.string().optional(),
  retryAfterMs: nonnegativeInteger.optional(),
});
export type SafeParams = z.infer<typeof safeParamsSchema>;
export const issueSchema = z.strictObject({
  path: z.string(),
  code: errorCodeSchema,
  params: safeParamsSchema,
  severity: z.enum(["error", "warning"]),
});
export type Issue = z.infer<typeof issueSchema>;
export const errorEnvelopeSchema = z.strictObject({
  statusCode: z.number().int().min(400).max(599),
  errorCode: errorCodeSchema,
  message: z.string(),
  params: safeParamsSchema,
  details: z.array(issueSchema),
  correlationId: z.uuidv4().regex(/^[0-9a-f-]+$/u),
});
export type ErrorEnvelope = z.infer<typeof errorEnvelopeSchema>;

/** Unknown exceptions never supply response text, codes, params or stack traces. */
export function internalError(correlationId: string): ErrorEnvelope {
  return errorEnvelopeSchema.parse({
    statusCode: 500,
    errorCode: "INTERNAL_ERROR",
    message: "An internal error occurred",
    params: {},
    details: [],
    correlationId,
  });
}

import { randomUUID } from "node:crypto";
import type { ErrorCode } from "@kabuki-neko/shared";
export const STORAGE_ADAPTER = Symbol("STORAGE_ADAPTER");
export const STORAGE_EXTENSIONS = {
  "image/jpeg": "jpg",
  "image/png": "png",
  "image/webp": "webp",
  "audio/mpeg": "mp3",
  "audio/ogg": "ogg",
  "audio/wav": "wav",
  "video/mp4": "mp4",
  "video/webm": "webm",
} as const;
export type StorageMime = keyof typeof STORAGE_EXTENSIONS;
export interface UploadOptions {
  buffer: Buffer;
  originalName: string;
  mimeType: StorageMime;
  folder: "covers" | "questions" | "audio" | "video";
  /** Reserved immutable key, otherwise generated by the adapter. */
  key?: string;
}
export interface StorageResult {
  key: string;
  publicUrl: string;
  sizeBytes: number;
  mimeType: StorageMime;
}
export interface StorageHead {
  exists: boolean;
  sizeBytes: number;
}
export interface StorageHealth {
  status: "up" | "down" | "unknown";
  checkedAt: number;
  errorCode: ErrorCode | null;
}
export interface IStorageAdapter {
  upload(options: UploadOptions): Promise<StorageResult>;
  delete(key: string): Promise<void>;
  readHead(key: string): Promise<StorageHead>;
  checkHealth(): Promise<StorageHealth>;
}
export function validateStorageKey(key: string): string {
  if (
    !/^(covers|questions|audio|video)\/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.(jpg|png|webp|mp3|ogg|wav|mp4|webm)$/.test(
      key,
    )
  )
    throw new Error("INVALID_REFERENCE");
  return key;
}
export function uploadKey(options: UploadOptions): string {
  const extension = STORAGE_EXTENSIONS[options.mimeType];
  if (
    !extension ||
    !["covers", "questions", "audio", "video"].includes(options.folder) ||
    (options.folder === "covers" && !options.mimeType.startsWith("image/")) ||
    (options.folder === "audio" && !options.mimeType.startsWith("audio/")) ||
    (options.folder === "video" && !options.mimeType.startsWith("video/"))
  )
    throw new Error("UNSUPPORTED_MEDIA");
  const key = validateStorageKey(options.key ?? `${options.folder}/${randomUUID()}.${extension}`);
  if (!key.startsWith(`${options.folder}/`) || !key.endsWith(`.${extension}`))
    throw new Error("INVALID_REFERENCE");
  return key;
}
export function isMissing(error: unknown): boolean {
  return typeof error === "object" && error !== null && "code" in error && error.code === "ENOENT";
}
